// Build a standalone Node runtime from the same engines used by the application.
// The resulting file is included in the static release; npm is needed only here.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const sources = [
  'src/engine/vendor/d3-delaunay.min.js', 'src/engine/vendor/clipper.js',
  'src/engine/territories.js', 'src/engine/zones.js',
  'src/engine/accessibility.js', 'src/engine/core.js',
  'src/engine/cache.js', 'src/engine/backup.js', 'src/engine/routing-osrm.js',
];
export async function buildRoutingEngine() {
  const parts = await Promise.all(sources.map(file => readFile(resolve(root, file), 'utf8')));
  const result = await transform(parts.map((code, index) => `/* Source: ${sources[index]} */\n${code}`).join('\n;\n'), {
    loader: 'js', target: 'es2022', platform: 'node',
    define: { module: 'undefined', exports: 'undefined' },
    legalComments: 'inline', minify: false, charset: 'utf8',
  });
  const exports = { A: 'HospitalAccessibility', O: 'HospitalRoutingOSRM', B: 'HospitalBackup', C: 'HospitalCore', L: 'HospitalLocalCache', T: 'HospitalTerritories' };
  const footer = Object.entries(exports).map(([name, global]) => `${name}: scope.${global}`).join(', ');
  await writeFile(resolve(root, 'local-routing/engine.cjs'),
    `/* Generated by local-routing/build-engine.mjs; edit src/engine instead. */\n'use strict';\nconst scope = { crypto: require('node:crypto').webcrypto };\n(function (window, self, globalThis, navigator) {\n${result.code}\n}).call(scope, scope, scope, scope, { userAgent: 'node chrome', appName: 'Netscape' });\nmodule.exports = { ${footer} };\n`);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildRoutingEngine();
  console.log('Built standalone OSRM routing engine');
}
